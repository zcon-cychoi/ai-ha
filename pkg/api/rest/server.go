// Package rest implements the AI-HA framework REST API server.
package rest

import (
	"context"
	_ "embed"
	"errors"
	"fmt"
	"net/http"
	"time"

	"github.com/cloud-barista/ai-ha/pkg/framework/agent"
	"github.com/cloud-barista/ai-ha/pkg/framework/inventory"
	"github.com/cloud-barista/ai-ha/pkg/framework/job"
	"github.com/cloud-barista/ai-ha/pkg/framework/restore"
	"github.com/labstack/echo/v4"
	"github.com/labstack/echo/v4/middleware"
	"github.com/rs/zerolog"
	"github.com/rs/zerolog/log"
)

// shutdownTimeout bounds how long in-flight requests may finish after the
// server has been asked to stop.
const shutdownTimeout = 10 * time.Second

// Listener timeouts. The API is reachable from the open internet, where a
// caller may open a connection and then stall; without deadlines such a
// connection is held until the process exits. Every handler here is short —
// readyz reads memory, a claim runs one query — so no legitimate request comes
// close to these bounds.
const (
	readHeaderTimeout = 10 * time.Second
	readTimeout       = 30 * time.Second
	writeTimeout      = 30 * time.Second
	idleTimeout       = 120 * time.Second
	maxHeaderBytes    = 64 << 10
)

// Rate limit applied per client address. The limits are far above real
// traffic: an orchestrator polls readyz about once a minute and an agent
// claims once or twice per restore.
const (
	rateLimitPerSecond = 10
	rateLimitBurst     = 20
	rateLimitExpiresIn = 3 * time.Minute
)

// bodyLimit caps the request body. The largest real request is an inventory
// report, which describes a handful of partitions in a couple of kilobytes;
// the inventory service caps the partition count well inside this, so an
// oversized report is refused with a reason rather than cut off.
const bodyLimit = "64K"

// swaggerSpec is the API contract generated by "make swag". It is served as-is
// so that a Swagger UI hosted elsewhere can load it.
//
//go:embed docs/swagger.json
var swaggerSpec []byte

// Config holds the REST server settings.
type Config struct {
	// Port is the TCP port the HTTP server listens on.
	Port int
	// TLSCertFile and TLSKeyFile are required: the server is reachable from the
	// internet and agents pin its certificate, so it never listens in plaintext.
	TLSCertFile string
	TLSKeyFile  string
	// Restore, when set, serves the rescue agent's restore endpoints.
	Restore *restore.Service
	// Agent, when set, serves agent enrolment and the job long poll.
	Agent *agent.Service
	// Jobs, when set alongside Agent, serves the job queue. Without it the long
	// poll only keeps agents marked alive.
	Jobs *job.Service
	// Inventory, when set alongside Agent, accepts agents' reports of what
	// their systems are made of. Without it backup targets have to be named by
	// hand.
	Inventory *inventory.Service
	// CORSOrigins are the browser origins allowed to call the API. Empty
	// leaves CORS off: agents are not browsers and never need it.
	CORSOrigins []string
	// EnableSwagger serves the OpenAPI document at /aiha/swagger.json. It
	// describes the API to anyone who can reach the port.
	EnableSwagger bool
}

// Run starts the REST API server and blocks until ctx is cancelled or the
// server fails. On cancellation it shuts down gracefully.
//
// @title AI-HA REST API
// @version 0.1.0
// @description REST API of the AI-HA framework, which backs up and restores workloads across clouds.
// @license.name Apache 2.0
// @license.url http://www.apache.org/licenses/LICENSE-2.0.html
// @BasePath /aiha
func Run(ctx context.Context, cfg Config) error {
	if cfg.TLSCertFile == "" || cfg.TLSKeyFile == "" {
		return errors.New("a TLS certificate and key are required to serve the API")
	}

	e := newEcho(cfg)
	// StartTLS serves e.TLSServer, which is the one that needs the deadlines.
	applyTimeouts(e.TLSServer)

	errCh := make(chan error, 1)
	go func() {
		addr := fmt.Sprintf(":%d", cfg.Port)
		log.Info().Int("port", cfg.Port).Msg("Starting REST API server over TLS")
		err := e.StartTLS(addr, cfg.TLSCertFile, cfg.TLSKeyFile)
		if err != nil && !errors.Is(err, http.ErrServerClosed) {
			errCh <- fmt.Errorf("failed to start REST API server: %w", err)
			return
		}
		errCh <- nil
	}()

	markReady(true)
	defer markReady(false)

	select {
	case err := <-errCh:
		return err
	case <-ctx.Done():
		log.Info().Msg("Shutting down REST API server")
		shutdownCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), shutdownTimeout)
		defer cancel()
		if err := e.Shutdown(shutdownCtx); err != nil {
			return fmt.Errorf("failed to shut down REST API server: %w", err)
		}
		return nil
	}
}

// NewHandler returns the API with cfg's routes as an http.Handler, without
// starting a server or using cfg's listener settings. Run serves the same
// routes.
func NewHandler(cfg Config) http.Handler {
	return newEcho(cfg)
}

// applyTimeouts bounds how long a connection may occupy the server.
func applyTimeouts(s *http.Server) {
	s.ReadHeaderTimeout = readHeaderTimeout
	s.ReadTimeout = readTimeout
	s.WriteTimeout = writeTimeout
	s.IdleTimeout = idleTimeout
	s.MaxHeaderBytes = maxHeaderBytes
}

// newEcho builds the Echo instance with middleware and routes.
func newEcho(cfg Config) *echo.Echo {
	e := echo.New()
	e.HideBanner = true
	e.HidePort = true
	e.Validator = newValidator()
	// The server is exposed directly, with no proxy in front, so the peer
	// address is the only trustworthy client identity. Echo's default falls
	// back to the X-Forwarded-For and X-Real-IP headers, which a caller sets
	// at will and could vary to slip past the rate limit below.
	e.IPExtractor = echo.ExtractIPDirect()

	e.Use(middleware.Recover())
	// Rate limiting sits outside the logger so that shed requests cost a map
	// lookup and nothing more. Inside it, a flood would be written to the log
	// line by line.
	e.Use(rateLimiter())
	e.Use(middleware.RequestID())
	e.Use(requestLogger())
	if len(cfg.CORSOrigins) > 0 {
		e.Use(middleware.CORSWithConfig(middleware.CORSConfig{
			AllowOrigins: cfg.CORSOrigins,
			AllowMethods: []string{http.MethodGet, http.MethodPost},
		}))
	}
	e.Use(middleware.BodyLimit(bodyLimit))

	g := e.Group("/aiha")
	g.GET("/readyz", RestGetReadyz)
	if cfg.EnableSwagger {
		g.GET("/swagger.json", RestGetSwaggerSpec)
	}
	if cfg.Restore != nil {
		h := &restoreHandler{svc: cfg.Restore}
		g.POST("/agent/restore/:recoveryId/claim", h.RestPostRestoreClaim)
		g.POST("/agent/restore/:recoveryId/progress", h.RestPostRestoreProgress)
		g.POST("/agent/restore/:recoveryId/result", h.RestPostRestoreResult)
	}
	if cfg.Agent != nil {
		h := &agentHandler{svc: cfg.Agent, jobs: cfg.Jobs, inventory: cfg.Inventory}
		auth := agentAuth(cfg.Agent)
		// Enrolment is the one agent route without a token: it is what issues
		// one. It is authorized by the registration token in its body.
		g.POST("/agent/register", h.RestPostAgentRegister)
		g.GET("/agent/jobs", h.RestGetAgentJobs, auth)
		if cfg.Jobs != nil {
			g.POST("/agent/jobs/:jobId/claim", h.RestPostAgentJobClaim, auth)
			g.POST("/agent/jobs/:jobId/progress", h.RestPostAgentJobProgress, auth)
			g.POST("/agent/jobs/:jobId/result", h.RestPostAgentJobResult, auth)
		}
		if cfg.Inventory != nil {
			g.POST("/agent/inventory", h.RestPostAgentInventory, auth)
		}
	}
	return e
}

// rateLimiter returns middleware that caps the request rate per client
// address. It bounds what a single source can cost the server, in particular
// the database query behind every claim. A distributed flood is out of its
// reach, and agents sharing one egress address share a budget.
func rateLimiter() echo.MiddlewareFunc {
	return middleware.RateLimiterWithConfig(middleware.RateLimiterConfig{
		Store: middleware.NewRateLimiterMemoryStoreWithConfig(
			middleware.RateLimiterMemoryStoreConfig{
				Rate:      rateLimitPerSecond,
				Burst:     rateLimitBurst,
				ExpiresIn: rateLimitExpiresIn,
			},
		),
		// Returning the error lets Echo render it as {"message": ...}, the
		// shape of model.SimpleMsg. Logging at debug keeps a flood out of the
		// log while leaving the addresses reachable when investigating one.
		DenyHandler: func(_ echo.Context, identifier string, _ error) error {
			log.Debug().Str("clientIp", identifier).Msg("Request rate limited")
			return echo.NewHTTPError(http.StatusTooManyRequests, "Too many requests, retry shortly")
		},
	})
}

// requestLogger returns middleware that reports each request through zerolog.
func requestLogger() echo.MiddlewareFunc {
	return middleware.RequestLoggerWithConfig(middleware.RequestLoggerConfig{
		LogMethod:    true,
		LogURI:       true,
		LogStatus:    true,
		LogLatency:   true,
		LogRequestID: true,
		LogError:     true,
		HandleError:  true,
		LogValuesFunc: func(_ echo.Context, v middleware.RequestLoggerValues) error {
			// The status, not the presence of an error, sets the level: a
			// scanner probing for paths that do not exist is not an error of
			// ours, and logging it as one buries the ones that are.
			level := zerolog.InfoLevel
			switch {
			case v.Status >= http.StatusInternalServerError:
				level = zerolog.ErrorLevel
			case v.Status >= http.StatusBadRequest:
				level = zerolog.WarnLevel
			}
			evt := log.WithLevel(level)
			if v.Error != nil {
				evt = evt.Err(v.Error)
			}
			evt.Str("method", v.Method).
				Str("uri", v.URI).
				Int("status", v.Status).
				Dur("latency", v.Latency).
				Str("requestId", v.RequestID).
				Msg("Request handled")
			return nil
		},
	})
}
